"""
LoRa Mesh Sandbox — Module 5: Resilience & Realism (Final Module)
==================================================================
Author: Simon Henson (with Claude)
Project: LoRa Mesh Network — Excelsior Farm telemetry sandbox

Module 5 layers three new behaviours on top of the Module 4 mesh:

    1. End-to-end (E2E) ACK + retry
       --------------------------------
       Module 4 only acknowledges hop-by-hop: the next-hop neighbour confirms
       it heard the packet.  That does NOT prove the data made it all the way
       to CONTROL — the ROUTER could ACK SUB_FAR successfully and then drop
       the forward.  Module 5 adds an end-to-end ACK generated by CONTROL,
       routed back through the mesh via reverse-route learning, and matched
       against the originator's pending state.  If the E2E ACK is missing
       within E2E_TIMEOUT_S the originator retries the whole packet.

    2. Fault tolerance
       ----------------
       At a configurable time we set ROUTER.failed = True.  All dispatch
       paths for that node become no-ops: no beacons, no forwards, no ACKs.
       After ROUTE_STALE_TIMEOUT_S (60 s, from routing.py) the subscribers'
       routing tables drop the stale entry.  SUB_FAR loses its route to
       CONTROL and stops transmitting cleanly (no crash, no infinite retry).
       Setting ROUTER.failed back to False simulates recovery — beacons
       resume and SUB_FAR rejoins.  SUB_NEAR (direct one-hop) is unaffected.

    3. Power / battery budget
       -----------------------
       Per-node energy accounting using SX1278 datasheet currents
       (see nodes.py: SX1278_TX_CURRENT_A, RX_CURRENT_A, SLEEP_CURRENT_A
       and V_SUPPLY_V = 3.3 V).  CONTROL and ROUTER are modelled as always-on
       listeners (idle = RX).  Subscribers are modelled as deep-sleep between
       heartbeats, with short RX windows for ACK reception.  At the end of
       a run the orchestrator projects average current (mA) and battery
       lifetime against a 2500 mAh reference cell.

Eight validation sections:
    1. E2E ACK happy path     — SUB_FAR delivers, gets E2E ACK back, no retries
    2. E2E retry on loss      — first E2E ACK dropped; originator retries; CONTROL dedupes
    3. ROUTER failure         — SUB_FAR detects stale route and stops TX
    4. ROUTER recovery        — SUB_FAR rejoins after ROUTER restarts beaconing
    5. SUB_NEAR independence  — SUB_NEAR unaffected during ROUTER outage
    6. Power budget per node  — 600 s realistic run, Joules + avg mA per node
    7. Battery life projection — days on a 2500 mAh cell for each node
    8. Full regression        — all Module 4 sections still pass with E2E ACK ON

Locked design parameters (additive to Module 4):
    E2E_ACK_TIMEOUT_S        = 4.0    # 2-hop RTT incl. single-TX-chain serialisation
    MAX_E2E_RETRIES          = 3
    REFERENCE_BATTERY_MAH    = 2500   # standard 18650 LiFePO4 single cell

Run:
    cd ~/Documents/LoRa_Sandbox
    source .venv/bin/activate
    python run_module5.py
"""

