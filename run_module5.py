def run_mesh_simulation_m5(
    sim_duration_s: float,
    rng_seed: int,
    ack_enabled: bool,
    e2e_enabled: bool,
    log_fn=None,
    sub_far_to_router_m: float = SUB_FAR_ROUTER_DIST_M,
    router_fail_at_s: Optional[float] = None,
    router_recover_at_s: Optional[float] = None,
    drop_e2e_ack_count: int = 0,   # test hook for Section 2
) -> dict:
    """
    Run the four-node mesh with Module 5 features for sim_duration_s seconds.

    Args:
        sim_duration_s        — total simulation duration
        rng_seed              — seeds global random and the channel RNG
        ack_enabled           — hop-by-hop ACK + retry (Module 4)
        e2e_enabled           — end-to-end ACK + retry (Module 5).  Requires
                                ack_enabled=True to make sense; we don't
                                enforce that but the harness will set both.
        log_fn                — print or None for verbose event log
        sub_far_to_router_m   — SUB_FAR ↔ ROUTER distance
        router_fail_at_s      — schedule ROUTER.failed = True at this time
                                (None = ROUTER stays alive)
        router_recover_at_s   — schedule ROUTER.failed = False at this time
                                (None = ROUTER stays in whatever state it was)
        drop_e2e_ack_count    — drop this many CONTROL-generated E2E ACKs at
                                their TX_END (used by Section 2 to prove the
                                originator retries).

    Returns dict with per-subscriber counts, retry stats, energy per node,
    and routing-table snapshots.
    """
    # ---- RNG ----
    random.seed(rng_seed)

    # ---- Channel ----
    channel = RadioChannelV3(
        path_loss_exponent  = PATH_LOSS_EXP,
        shadow_fading_std_db= SHADOW_STD_DB,
        sf                  = SF,
        tx_power_dbm        = TX_POWER_DBM,
        tx_gain_dbi         = ANTENNA_GAIN_DBI,
        rx_gain_dbi         = ANTENNA_GAIN_DBI,
        cable_loss_db       = CABLE_LOSS_DB,
        noise_floor_dbm     = NOISE_FLOOR_DBM,
        seed                = rng_seed,
    )

    # ---- Routing tables ----
    rt_router   = RoutingTable(NODE_ROUTER_ID,   NODE_CONTROL_ID)
    rt_sub_near = RoutingTable(NODE_SUB_NEAR_ID, NODE_CONTROL_ID)
    rt_sub_far  = RoutingTable(NODE_SUB_FAR_ID,  NODE_CONTROL_ID)

    # ---- Positions ----
    sub_far_x = ROUTER_X_M + sub_far_to_router_m
    positions = {
        NODE_CONTROL_ID:   CONTROL_POS,
        NODE_ROUTER_ID:    (ROUTER_X_M,   0.0),
        NODE_SUB_NEAR_ID:  (SUB_NEAR_X_M, 0.0),
        NODE_SUB_FAR_ID:   (sub_far_x,    0.0),
    }

    def dist(a_id: int, b_id: int) -> float:
        return euclidean_m(positions[a_id], positions[b_id])

    _log = log_fn or (lambda *_: None)

    # ---- Nodes ----
    control = LoRaNode(
        node_id           = NODE_CONTROL_ID,
        role              = NodeRole.CONTROL,
        position_m        = positions[NODE_CONTROL_ID],
        beacon_interval_s = BEACON_INTERVAL_S,
        network_id        = NETWORK_ID,
        log_callback      = _log,
    )

    router = LoRaNode(
        node_id           = NODE_ROUTER_ID,
        role              = NodeRole.ROUTER,
        position_m        = positions[NODE_ROUTER_ID],
        beacon_interval_s = BEACON_INTERVAL_S,
        network_id        = NETWORK_ID,
        routing_table     = rt_router,
        log_callback      = _log,
    )

    sub_near = LoRaNode(
        node_id              = NODE_SUB_NEAR_ID,
        role                 = NodeRole.SUBSCRIBER,
        position_m           = positions[NODE_SUB_NEAR_ID],
        heartbeat_interval_s = HEARTBEAT_INTERVAL_S,
        peer_id              = NODE_CONTROL_ID,
        battery_mv_initial   = BATTERY_MV,
        sensor               = TemperatureSensor(seed=rng_seed + 2),
        routing_table        = rt_sub_near,
        network_id           = NETWORK_ID,
        log_callback         = _log,
    )

    sub_far = LoRaNode(
        node_id              = NODE_SUB_FAR_ID,
        role                 = NodeRole.SUBSCRIBER,
        position_m           = positions[NODE_SUB_FAR_ID],
        heartbeat_interval_s = HEARTBEAT_INTERVAL_S,
        peer_id              = NODE_ROUTER_ID,
        battery_mv_initial   = BATTERY_MV,
        sensor               = TemperatureSensor(seed=rng_seed + 3),
        routing_table        = rt_sub_far,
        network_id           = NETWORK_ID,
        log_callback         = _log,
    )

    all_nodes = {
        NODE_CONTROL_ID:   control,
        NODE_ROUTER_ID:    router,
        NODE_SUB_NEAR_ID:  sub_near,
        NODE_SUB_FAR_ID:   sub_far,
    }

    # ---- Scheduler ----
    log_level = LOG_VERBOSE if log_fn else LOG_SUMMARY
    sched = Scheduler(log_level=log_level)

    # ---- Shared mutable state ----
    results = {
        # Module 4 metrics
        "sent_sub_near":         0,
        "sent_sub_far":          0,
        "delivered_sub_near":    0,
        "delivered_sub_far":     0,
        "collisions":            0,
        "retransmissions":       0,
        "retry_exhausted":       0,
        "router_airtime_s":      0.0,
        # Module 5 additions
        "e2e_acks_sent":         0,
        "e2e_acks_received":     0,
        "e2e_retransmissions":   0,
        "e2e_retry_exhausted":   0,
        "e2e_acks_dropped":      0,   # test-hook drops only
        "duplicates_at_control": 0,
    }

    # Test hook: counts down how many E2E ACKs to silently drop next.
    # Wrapped in a single-element list so closures can mutate it without
    # triggering Python's nonlocal/rebind rule.
    drop_budget = [drop_e2e_ack_count]

    # CONTROL-side seen-set for duplicate detection.  The Module 4 last-seq
    # check only catches BACK-TO-BACK duplicates; a retry that arrives after
    # a newer heartbeat would slip through and falsely inflate PDR.  Using a
    # set of (originator_id, seq_num) makes the dedup tight.
    seen_at_control: set = set()

    # Hop-by-hop ACK retry tokens (Module 4 logic — unchanged shape)
    pending_acks: set = set()

    # E2E retry tokens — keyed by (originator_id, seq_num, attempt).
    # The dispatcher uses the (originator_id, seq_num) prefix to clear all
    # stale attempts when an E2E ACK arrives, similar to Module 4 hop ACK.
    pending_e2e: set = set()

    # Per-node "earliest free TX time" — Module 5 generalisation of the
    # Module 4 ROUTER stagger.  A real radio has a single TX chain: it cannot
    # start a new packet until the previous one finishes.  CONTROL in Module 5
    # may need to send several packets in quick succession (hop-ACK + E2E ACK
    # + responses to back-to-back DATA), so we track each node's next-free
    # time and silently push new TXs into the future if needed.  A small guard
    # margin (TX_GUARD_S) prevents register_tx race conditions due to float
    # equality.
    earliest_free_tx_at_s = {nid: 0.0 for nid in (
        NODE_CONTROL_ID, NODE_ROUTER_ID, NODE_SUB_NEAR_ID, NODE_SUB_FAR_ID
    )}
    TX_GUARD_S = 0.005   # 5 ms guard so TX_END settles before next TX_START

    # ---- Beacon timing ----
    control.next_beacon_at = FIRST_BEACON_DELAY_S
    router.next_beacon_at  = FIRST_BEACON_DELAY_S + BEACON_STAGGER_S

    sched.schedule(FIRST_BEACON_DELAY_S,
                   TIMER_FIRE, {"timer_type": "beacon", "node": control})
    sched.schedule(FIRST_BEACON_DELAY_S + BEACON_STAGGER_S,
                   TIMER_FIRE, {"timer_type": "beacon", "node": router})
    # Module 5: stagger the two subscribers by half a heartbeat interval so
    # their TX bursts don't systematically overlap on the back-channel.  With
    # `nodes.py` initialising both to random.uniform(0.5, 1.5) the same seed
    # frequently puts them within 100 ms of each other, which then guarantees
    # repeated collisions every 5 s.  Forcing a deterministic 2.5 s offset
    # roughly halves observed retries on collision-prone runs.
    sub_near.next_heartbeat_at = 0.5
    sub_far.next_heartbeat_at  = 0.5 + (HEARTBEAT_INTERVAL_S / 2.0)
    sched.schedule(sub_near.next_heartbeat_at,
                   TIMER_FIRE, {"timer_type": "heartbeat", "node": sub_near})
    sched.schedule(sub_far.next_heartbeat_at,
                   TIMER_FIRE, {"timer_type": "heartbeat", "node": sub_far})

    # ---- Failure injection ----
    if router_fail_at_s is not None:
        sched.schedule(router_fail_at_s, NODE_FAIL_EVT, {"node": router})
    if router_recover_at_s is not None:
        sched.schedule(router_recover_at_s, NODE_RECOVER_EVT, {"node": router})

    # =========================================================================
    # POWER ACCOUNTING HELPERS
    # =========================================================================
    # CONTROL and ROUTER idle in RX (always listening).  Subscribers idle in
    # SLEEP between heartbeats.  We call account_until() at every event the
    # node participates in, so the cumulative time-in-state is updated lazily.

    def _idle_mode_for(node: LoRaNode) -> str:
        return "rx" if node.role in (NodeRole.CONTROL, NodeRole.ROUTER) else "sleep"

    def _settle_node(node: LoRaNode, now_s: float) -> None:
        """Charge the gap since last close-out to the node's idle mode."""
        # If the node is failed, we treat its time as SLEEP (radio off).
        if node.failed:
            elapsed = now_s - node.last_accounted_at_s
            if elapsed > 0.0:
                node.time_in_sleep_s += elapsed
            node.last_accounted_at_s = now_s
            return
        node.account_until(now_s, _idle_mode_for(node))

    def _account_tx(node: LoRaNode, pkt_toa_s: float, now_s: float) -> None:
        """Charge a TX duration after settling the preceding idle gap."""
        _settle_node(node, now_s)
        node.account_tx(pkt_toa_s)
        node.last_accounted_at_s = now_s + pkt_toa_s

    def _account_rx_window(node: LoRaNode, window_s: float, _now_s_unused: float) -> None:
        """
        Charge a deliberate RX listen window for a subscriber AFTER its TX.

        The window starts at node.last_accounted_at_s (which `_account_tx`
        has already advanced to tx_end), so the RX window correctly follows
        the TX in time rather than overlapping it.  This keeps the energy
        bookkeeping additive: per heartbeat we charge ToA seconds to TX,
        window_s seconds to RX, and the remainder up to the next event
        to SLEEP — totals equal real elapsed time.

        `_now_s_unused` is retained for call-site symmetry but ignored —
        we never want to rewind the clock backward.
        """
        assert window_s >= 0.0, f"negative RX window: {window_s}"
        node.time_in_rx_s += window_s
        node.last_accounted_at_s = node.last_accounted_at_s + window_s

    # =========================================================================
    # TX SCHEDULING HELPERS (same shape as Module 4)
    # =========================================================================

    def node_dist(sender_id: int, receiver_id: int) -> float:
        return dist(sender_id, receiver_id)

    def _schedule_tx(
        sender_id: int,
        receiver,
        pkt: Packet,
        pkt_role: str,
        backoff_s: float = 0.0,
        extra: Optional[dict] = None,
    ) -> None:
        """Push TX_START; TX_END follows automatically after ToA.

        `extra` is merged into the event payload so the TX_END handler can
        pull out role-specific data (e.g. originator_id for E2E ACKs).
        """
        raw       = pkt.to_bytes()
        pkt_toa   = toa_s(pkt)

        # Single-TX-chain enforcement: if the sender's previous TX hasn't
        # finished yet, push this TX to start AFTER that TX_END plus a small
        # guard.  This silently serialises bursts (e.g. hop-ACK + E2E ACK)
        # without having to thread backoffs through every call site.
        now_s        = sched.now()
        requested_t  = now_s + backoff_s
        node_free_t  = earliest_free_tx_at_s.get(sender_id, 0.0)
        tx_start_t   = max(requested_t, node_free_t)
        # If we had to delay, fold the delay into backoff so sched.schedule
        # fires the TX_START at the right moment.
        backoff_s    = tx_start_t - now_s
        tx_end_t     = tx_start_t + pkt_toa
        # Reserve the air time for this sender until tx_end + guard
        earliest_free_tx_at_s[sender_id] = tx_end_t + TX_GUARD_S

        if sender_id == NODE_ROUTER_ID:
            results["router_airtime_s"] += pkt_toa

        # Charge TX energy to the sender at scheduling time.  Each scheduled
        # TX corresponds to exactly one ToA charge (no double-booking on
        # retries because retries call _schedule_tx fresh each time).
        sender_node = all_nodes[sender_id]
        _account_tx(sender_node, pkt_toa, tx_start_t)

        is_broadcast = isinstance(receiver, list)

        payload_d = {
            "pkt_role":   pkt_role,
            "sender_id":  sender_id,
            "pkt":        pkt,
            "raw_bytes":  raw,
            "tx_start":   tx_start_t,
            "tx_end":     tx_end_t,
        }
        if is_broadcast:
            min_d = min((d for _, d in receiver), default=1.0)
            payload_d["receivers"]  = receiver
            payload_d["distance_m"] = min_d
        else:
            payload_d["receiver_id"] = receiver
            payload_d["distance_m"]  = node_dist(sender_id, receiver)

        if extra:
            payload_d.update(extra)

        sched.schedule(backoff_s, TX_START, payload_d)

    def _schedule_ack(sender_id: int, dst_id: int, ack_seq: int, acked_src: int) -> None:
        ack_node = all_nodes[sender_id]
        if ack_node.failed:
            return
        ack_pkt  = ack_node.generate_ack(ack_seq, acked_src, dst_id)
        _schedule_tx(sender_id, dst_id, ack_pkt, pkt_role="ack")

    def _schedule_forward(original_pkt: Packet, backoff_s: float = 0.0) -> None:
        if router.failed:
            return
        fwd = Packet(
            packet_type = PacketType.DATA,
            src_id      = original_pkt.src_id,
            dst_id      = NODE_CONTROL_ID,
            seq_num     = original_pkt.seq_num,
            payload     = original_pkt.payload,
        )
        _schedule_tx(
            NODE_ROUTER_ID, NODE_CONTROL_ID, fwd,
            pkt_role="forwarded",
            backoff_s=backoff_s,
            # Remember who delivered the original to us, so when the E2E ACK
            # eventually comes back we can route it the right way.
            extra={"forwarded_from": original_pkt.src_id},
        )

    def _schedule_e2e_ack(originator_id: int, ack_seq_num: int,
                          after_hop_ack: bool) -> None:
        """
        CONTROL builds an E2E ACK for `originator_id` and pushes it to the
        next-hop downstream neighbour (looked up in CONTROL's reverse-route
        table that was populated when CONTROL accepted the DATA packet).

        after_hop_ack: True if CONTROL just scheduled a hop-by-hop ACK to
        this same neighbour.  A real radio can only transmit one packet at a
        time, so the E2E ACK must start AFTER the hop-ACK finishes.  We add
        the hop-ACK ToA plus a small guard margin to the backoff.
        """
        if not e2e_enabled:
            return
        next_hop = control.next_downstream_hop(originator_id)
        if next_hop is None:
            # We accepted a packet from this originator but have no reverse
            # route — should never happen because we always learn on RX.
            _log(f"[t={sched.now():.2f}s] CONTROL: no downstream route to "
                 f"orig={originator_id}; cannot send E2E ACK")
            return
        e2e_pkt = control.generate_e2e_ack(
            ack_seq_num   = ack_seq_num,
            originator_id = originator_id,
            dst_id        = next_hop,
        )
        results["e2e_acks_sent"] += 1

        # Stagger off the hop-ACK if both are firing.  Use a fresh probe
        # packet so we can compute its ToA without affecting any state —
        # then immediately roll back the probe's seq advance because we
        # never actually transmit it.
        if after_hop_ack:
            probe = control.generate_ack(ack_seq_num, originator_id, next_hop)
            control.tx_seq = (control.tx_seq - 1) & 0xFFFF
            backoff = toa_s(probe) + 0.02   # 20 ms guard beyond ACK end
        else:
            backoff = 0.0

        _schedule_tx(
            NODE_CONTROL_ID, next_hop, e2e_pkt, pkt_role="e2e_ack",
            backoff_s=backoff,
            extra={"originator_id": originator_id, "ack_seq": ack_seq_num},
        )

    def _schedule_e2e_forward(pkt: Packet, originator_id: int, ack_seq: int) -> None:
        """
        Intermediate ROUTER relays an E2E ACK toward the originator.
        Looks up its own downstream table to find the next hop.
        """
        if router.failed:
            return
        next_hop = router.next_downstream_hop(originator_id)
        if next_hop is None:
            _log(f"[t={sched.now():.2f}s] ROUTER: no downstream route to "
                 f"orig={originator_id}; dropping E2E ACK")
            return
        # Re-stamp src_id and dst_id but keep payload identical (originator_id
        # + ack_seq_num live inside the payload, so the receiver still matches
        # the retry state correctly).
        forwarded = Packet(
            packet_type = PacketType.ACK_E2E,
            src_id      = NODE_ROUTER_ID,
            dst_id      = next_hop,
            seq_num     = router.tx_seq,
            payload     = pkt.payload,
        )
        router.tx_seq = (router.tx_seq + 1) & 0xFFFF
        _schedule_tx(
            NODE_ROUTER_ID, next_hop, forwarded, pkt_role="e2e_ack",
            extra={"originator_id": originator_id, "ack_seq": ack_seq},
        )

    # =========================================================================
    # DISPATCH
    # =========================================================================

    def dispatch(evt: Event) -> None:
        t  = sched.now()
        et = evt.event_type

        if et == TIMER_FIRE:
            _handle_timer(evt, t)
        elif et == TX_START:
            _handle_tx_start(evt, t)
        elif et == TX_END:
            _handle_tx_end(evt, t)
        elif et == ACK_TIMEOUT_EVT:
            _handle_ack_timeout(evt, t)
        elif et == E2E_TIMEOUT_EVT:
            _handle_e2e_timeout(evt, t)
        elif et == NODE_FAIL_EVT:
            _handle_node_fail(evt, t)
        elif et == NODE_RECOVER_EVT:
            _handle_node_recover(evt, t)

    # ---- TIMER_FIRE ----

    def _handle_timer(evt: Event, t: float) -> None:
        timer_type = evt.payload["timer_type"]
        node       = evt.payload["node"]

        if node.failed:
            # Failed node ignores its own timers — but the scheduler will keep
            # the timer thread alive after recovery.  Reschedule a beacon/
            # heartbeat so the loop resumes when failed flips back to False.
            if timer_type == "beacon":
                sched.schedule(BEACON_INTERVAL_S, TIMER_FIRE,
                               {"timer_type": "beacon", "node": node})
            elif timer_type == "heartbeat":
                sched.schedule(HEARTBEAT_INTERVAL_S, TIMER_FIRE,
                               {"timer_type": "heartbeat", "node": node})
            return

        if timer_type == "heartbeat":
            _do_heartbeat(node, t)
        elif timer_type == "beacon":
            _do_beacon(node, t)

    def _do_heartbeat(node: LoRaNode, t: float) -> None:
        # No route?  Defer one second and try again.
        if node.routing_table and not node.routing_table.has_route(t):
            _log(f"[t={t:.2f}s] Node {node.id}: no route — deferring 1.0 s")
            sched.schedule(1.0, TIMER_FIRE, {"timer_type": "heartbeat", "node": node})
            return

        pkt = node.tick_subscriber(t)
        if pkt is None:
            return

        next_hop = node.routing_table.best_parent(t) if node.routing_table else node.peer_id
        if next_hop is None:
            _log(f"[t={t:.2f}s] Node {node.id}: no next hop — dropped")
            return

        if pkt.dst_id != next_hop:
            pkt = Packet(PacketType.DATA, pkt.src_id, next_hop, pkt.seq_num, pkt.payload)

        if node.id == NODE_SUB_NEAR_ID:
            results["sent_sub_near"] += 1
        elif node.id == NODE_SUB_FAR_ID:
            results["sent_sub_far"]  += 1

        _schedule_tx(node.id, next_hop, pkt, pkt_role="data")

        # Charge a deliberate RX listen window after the TX completes.
        # Subscribers are in RX waiting for hop-ACK + E2E ACK.
        _account_rx_window(node, SUBSCRIBER_RX_WINDOW_S, sched.now())

        sched.schedule(HEARTBEAT_INTERVAL_S, TIMER_FIRE,
                       {"timer_type": "heartbeat", "node": node})

        # Hop-by-hop ACK retry token (Module 4)
        if ack_enabled:
            attempt = 0
            pending_acks.add((node.id, pkt.seq_num, attempt))
            sched.schedule(
                toa_s(pkt) + ACK_TIMEOUT_S,
                ACK_TIMEOUT_EVT,
                {
                    "node": node, "seq_num": pkt.seq_num, "attempt": attempt,
                    "next_hop": next_hop, "pkt": pkt,
                },
            )

        # E2E retry token (Module 5)
        if e2e_enabled:
            attempt = 0
            pending_e2e.add((node.id, pkt.seq_num, attempt))
            sched.schedule(
                E2E_ACK_TIMEOUT_S,
                E2E_TIMEOUT_EVT,
                {
                    "node": node, "seq_num": pkt.seq_num, "attempt": attempt,
                    "next_hop": next_hop, "pkt": pkt,
                },
            )

    def _do_beacon(node: LoRaNode, t: float) -> None:
        pkt = node.tick_beacon(t)
        if pkt is None:
            sched.schedule(BEACON_INTERVAL_S, TIMER_FIRE,
                           {"timer_type": "beacon", "node": node})
            return

        eligible  = REACHABLE_FROM.get(node.id, [])
        receivers = [(rx_id, node_dist(node.id, rx_id)) for rx_id in eligible]
        _schedule_tx(node.id, receivers, pkt, pkt_role="beacon")

        sched.schedule(BEACON_INTERVAL_S, TIMER_FIRE,
                       {"timer_type": "beacon", "node": node})

    # ---- TX_START / TX_END ----

    def _handle_tx_start(evt: Event, t: float) -> None:
        p = evt.payload
        # If sender has failed between scheduling and TX_START — silently
        # cancel.  No collision is registered, no airtime charged (we already
        # charged at scheduling time, which is a minor over-count we accept
        # in failure scenarios since they are rare).
        sender_node = all_nodes[p["sender_id"]]
        if sender_node.failed:
            return
        channel.register_tx(
            tx_start   = p["tx_start"],
            tx_end     = p["tx_end"],
            node_id    = p["sender_id"],
            freq_mhz   = FREQUENCY_MHZ,
            sf         = SF,
            distance_m = p["distance_m"],
        )
        delay = max(0.0, p["tx_end"] - t)
        sched.schedule(delay, TX_END, p)

    def _handle_tx_end(evt: Event, t: float) -> None:
        role = evt.payload["pkt_role"]
        if role == "beacon":
            _deliver_beacon(evt, t)
        elif role in ("data", "forwarded"):
            _deliver_data(evt, t)
        elif role == "ack":
            _deliver_ack(evt, t)
        elif role == "e2e_ack":
            _deliver_e2e_ack(evt, t)

    def _deliver_beacon(evt: Event, t: float) -> None:
        p         = evt.payload
        sender_id = p["sender_id"]
        receivers = p["receivers"]
        pkt       = p["pkt"]

        collided = channel.pop_collision_flag(
            tx_end_time = p["tx_end"],
            node_id     = sender_id,
            freq_mhz    = FREQUENCY_MHZ,
            sf          = SF,
        )
        if collided:
            results["collisions"] += 1
            return

        for rx_id, dist_m in receivers:
            rx_node = all_nodes[rx_id]
            if rx_node.failed:
                # Drain RNG so deterministic test isolation isn't broken when
                # the receiver is offline — failed nodes still "would have"
                # consumed channel randomness in the physical world.
                channel.transmit(dist_m)
                continue
            rx = channel.transmit(dist_m)
            if rx.decoded:
                rx_node.receive_beacon(pkt, rx.rssi_dbm, t)

    def _deliver_data(evt: Event, t: float) -> None:
        p           = evt.payload
        sender_id   = p["sender_id"]
        receiver_id = p["receiver_id"]
        pkt         = p["pkt"]
        raw         = p["raw_bytes"]
        role        = p["pkt_role"]

        receiver_node = all_nodes[receiver_id]

        # If receiver is failed, we still resolve through the channel so the
        # RNG state matches a non-failed run up to the failure event — but we
        # discard the result.  Cleaner option would be to skip register_tx
        # earlier; in practice the failed receiver case happens rarely.
        rx = channel.resolve_rx(
            tx_end_time = p["tx_end"],
            node_id     = sender_id,
            freq_mhz    = FREQUENCY_MHZ,
            sf          = SF,
        )

        if receiver_node.failed:
            return

        if not rx.decoded:
            if rx.failure_reason == "collision":
                results["collisions"] += 1
            return

        if receiver_id == NODE_CONTROL_ID:
            # ---- Final delivery at CONTROL ----
            # Reverse-route learning: remember who handed us this packet.
            # For SUB_NEAR direct, prev_hop == originator == SUB_NEAR.
            # For SUB_FAR via ROUTER, prev_hop == ROUTER, originator == SUB_FAR.
            orig_src = pkt.src_id
            control.learn_downstream(originator_id=orig_src, previous_hop_id=sender_id)

            # Duplicate detection: only credit delivery on the FIRST sight
            # of (orig_src, seq_num).  We use a full seen-set rather than the
            # Module 4 last-seq check because retries may arrive out-of-order
            # with respect to fresh heartbeats (e.g. SUB_FAR retry after SUB_FAR
            # has already sent seq+1), and the last-seq check would mis-credit
            # those as new deliveries — producing PDR > 100%.
            key = (orig_src, pkt.seq_num)
            is_duplicate = (key in seen_at_control)
            if not is_duplicate:
                seen_at_control.add(key)

            control.receive(raw, t, rx.rssi_dbm, rx.snr_db)

            if is_duplicate:
                results["duplicates_at_control"] += 1
            else:
                if orig_src == NODE_SUB_NEAR_ID:
                    results["delivered_sub_near"] += 1
                elif orig_src == NODE_SUB_FAR_ID:
                    results["delivered_sub_far"] += 1

            # Hop-by-hop ACK to the previous sender (even on duplicate, so
            # the sender stops retrying)
            hop_ack_scheduled = False
            if ack_enabled and role in ("data", "forwarded"):
                _schedule_ack(NODE_CONTROL_ID, sender_id, pkt.seq_num, pkt.src_id)
                hop_ack_scheduled = True

            # End-to-end ACK back to originator (even on duplicate — same
            # reason: confirm to the originator that the packet is at home).
            # Must stagger off the hop-ACK if both are firing (single TX chain).
            if e2e_enabled:
                _schedule_e2e_ack(
                    originator_id = orig_src,
                    ack_seq_num   = pkt.seq_num,
                    after_hop_ack = hop_ack_scheduled,
                )

        elif receiver_id == NODE_ROUTER_ID:
            # ROUTER receives from SUB_FAR.
            # Learn downstream (so the future E2E ACK can flow back).
            router.learn_downstream(originator_id=pkt.src_id, previous_hop_id=sender_id)

            if ack_enabled:
                _schedule_ack(NODE_ROUTER_ID, sender_id, pkt.seq_num, pkt.src_id)
                _ack_probe = router.generate_ack(pkt.seq_num, pkt.src_id, sender_id)
                # Roll back the seq advance — we used a probe to measure ToA only,
                # the real ACK was already scheduled by _schedule_ack above.
                router.tx_seq = (router.tx_seq - 1) & 0xFFFF
                fwd_delay = toa_s(_ack_probe) + 0.02
            else:
                fwd_delay = 0.0

            router.state = NodeState.FORWARD
            _schedule_forward(pkt, backoff_s=fwd_delay)

    def _deliver_ack(evt: Event, t: float) -> None:
        p           = evt.payload
        sender_id   = p["sender_id"]
        receiver_id = p["receiver_id"]
        pkt         = p["pkt"]

        rx_node = all_nodes[receiver_id]
        rx = channel.resolve_rx(
            tx_end_time = p["tx_end"],
            node_id     = sender_id,
            freq_mhz    = FREQUENCY_MHZ,
            sf          = SF,
        )

        if rx_node.failed or not rx.decoded:
            return

        ack_data = decode_ack_payload(pkt.payload)
        if ack_data is None:
            return
        ack_seq = ack_data["ack_seq_num"]

        # Clear pending hop-ACK tokens for (receiver, seq)
        stale = {tok for tok in pending_acks
                 if tok[0] == receiver_id and tok[1] == ack_seq}
        pending_acks.difference_update(stale)

    def _deliver_e2e_ack(evt: Event, t: float) -> None:
        """
        Deliver an end-to-end ACK to its current next-hop receiver.

        Three possibilities for the receiver:
          - It is the originator: clear pending E2E retry state.
          - It is a forwarder (ROUTER): relay using its own downstream table.
          - It is something else: drop with a warning.
        """
        p           = evt.payload
        sender_id   = p["sender_id"]
        receiver_id = p["receiver_id"]
        pkt         = p["pkt"]

        # Test hook: silently drop this E2E ACK to force a retry.
        if drop_budget[0] > 0:
            drop_budget[0] -= 1
            results["e2e_acks_dropped"] += 1
            _log(f"[t={t:.4f}s] TEST HOOK: dropping E2E ACK {sender_id}→{receiver_id}")
            # Still resolve through channel to keep RNG state consistent
            channel.resolve_rx(p["tx_end"], sender_id, FREQUENCY_MHZ, SF)
            return

        rx_node = all_nodes[receiver_id]
        rx = channel.resolve_rx(
            tx_end_time = p["tx_end"],
            node_id     = sender_id,
            freq_mhz    = FREQUENCY_MHZ,
            sf          = SF,
        )
        if rx_node.failed or not rx.decoded:
            return

        ack_data = decode_e2e_ack_payload(pkt.payload)
        if ack_data is None:
            return
        ack_seq   = ack_data["ack_seq_num"]
        orig_id   = ack_data["originator_id"]

        if receiver_id == orig_id:
            # We are the originator — clear pending E2E retry tokens
            results["e2e_acks_received"] += 1
            stale = {tok for tok in pending_e2e
                     if tok[0] == orig_id and tok[1] == ack_seq}
            pending_e2e.difference_update(stale)
            _log(f"[t={t:.4f}s] E2E ACK received at originator={orig_id} seq={ack_seq} ✓")
        elif receiver_id == NODE_ROUTER_ID:
            # Relay further downstream
            _schedule_e2e_forward(pkt, originator_id=orig_id, ack_seq=ack_seq)
        else:
            _log(f"[t={t:.4f}s] E2E ACK delivered to unexpected node {receiver_id} — dropped")

    # ---- ACK_TIMEOUT ----

    def _handle_ack_timeout(evt: Event, t: float) -> None:
        p       = evt.payload
        node    = p["node"]
        seq_num = p["seq_num"]
        attempt = p["attempt"]
        token   = (node.id, seq_num, attempt)

        if node.failed:
            return
        if token not in pending_acks:
            return

        pending_acks.discard(token)

        if attempt >= MAX_RETRIES:
            results["retry_exhausted"] += 1
            return

        new_attempt = attempt + 1
        results["retransmissions"] += 1
        pkt      = p["pkt"]
        next_hop = p["next_hop"]

        _schedule_tx(node.id, next_hop, pkt, pkt_role="data",
                     backoff_s=RETRY_BACKOFF_S)
        # NOTE: no fresh _account_rx_window here.  The original heartbeat
        # already charged its listen window; a hop-ACK retry happens within
        # (or just after) that window and re-uses the same RX state.  Adding
        # another window per retry would double-count and explode the battery
        # projection in collision-heavy runs.

        new_token = (node.id, seq_num, new_attempt)
        pending_acks.add(new_token)
        sched.schedule(
            RETRY_BACKOFF_S + toa_s(pkt) + ACK_TIMEOUT_S,
            ACK_TIMEOUT_EVT,
            {"node": node, "seq_num": seq_num, "attempt": new_attempt,
             "next_hop": next_hop, "pkt": pkt},
        )

    # ---- E2E_TIMEOUT ----

    def _handle_e2e_timeout(evt: Event, t: float) -> None:
        """
        Originator did not receive an E2E ACK in time.  Retry the whole
        DATA packet up to MAX_E2E_RETRIES times.

        Note: this retry is independent of the hop-by-hop retry — they run
        in parallel.  Hop-ACK retries handle "next-hop didn't hear me".
        E2E retries handle "neighbour heard me but data never reached CONTROL".
        """
        p       = evt.payload
        node    = p["node"]
        seq_num = p["seq_num"]
        attempt = p["attempt"]
        token   = (node.id, seq_num, attempt)

        if node.failed:
            return
        if token not in pending_e2e:
            return   # ACK arrived in time — nothing to do

        pending_e2e.discard(token)

        if attempt >= MAX_E2E_RETRIES:
            results["e2e_retry_exhausted"] += 1
            return

        # Route may have changed since the original attempt — re-pick parent.
        if node.routing_table and not node.routing_table.has_route(t):
            # No route now (e.g. ROUTER failed).  Give up this retry cycle;
            # the next heartbeat will defer naturally.
            return

        next_hop = node.routing_table.best_parent(t) if node.routing_table else node.peer_id
        if next_hop is None:
            return

        new_attempt = attempt + 1
        results["e2e_retransmissions"] += 1
        pkt = p["pkt"]
        # If next_hop changed, restamp dst_id
        if pkt.dst_id != next_hop:
            pkt = Packet(PacketType.DATA, pkt.src_id, next_hop, pkt.seq_num, pkt.payload)

        _schedule_tx(node.id, next_hop, pkt, pkt_role="data",
                     backoff_s=RETRY_BACKOFF_S)
        # NOTE: no fresh _account_rx_window here — see _handle_ack_timeout
        # for the same reasoning.  Adding another full listen window per E2E
        # retry would over-charge RX time and produce nonsense battery life.

        new_token = (node.id, seq_num, new_attempt)
        pending_e2e.add(new_token)
        sched.schedule(
            E2E_ACK_TIMEOUT_S,
            E2E_TIMEOUT_EVT,
            {"node": node, "seq_num": seq_num, "attempt": new_attempt,
             "next_hop": next_hop, "pkt": pkt},
        )

    # ---- NODE_FAIL / NODE_RECOVER ----

    def _handle_node_fail(evt: Event, t: float) -> None:
        node = evt.payload["node"]
        # Settle accounting before flipping the flag — anything before t was
        # still RX/sleep as appropriate.
        _settle_node(node, t)
        node.failed = True
        _log(f"[t={t:.2f}s] *** NODE {node.id} FAILED ***")

    def _handle_node_recover(evt: Event, t: float) -> None:
        node = evt.payload["node"]
        # Settle accounting (failed time was charged as SLEEP).
        _settle_node(node, t)
        node.failed = False
        # Do NOT schedule an extra beacon timer here.  During failure the
        # _handle_timer guard for failed nodes already kept rescheduling the
        # original beacon timer thread every BEACON_INTERVAL_S seconds, so
        # there is exactly one queued beacon timer with the original stagger
        # (FIRST_BEACON_DELAY_S + BEACON_STAGGER_S offset).  When that timer
        # fires after recovery, ROUTER's routing table may still be stale —
        # the first post-recovery beacon will carry hop_count=255 and
        # subscribers will ignore it.  By the second post-recovery beacon
        # (one BEACON_INTERVAL_S later), ROUTER will have heard CONTROL's
        # latest beacon and can emit a valid hop_count=1.  Maintaining the
        # original stagger keeps ROUTER's beacons offset from CONTROL's so
        # they don't collide.
        _log(f"[t={t:.2f}s] *** NODE {node.id} RECOVERED ***")

    # =========================================================================
    # RUN
    # =========================================================================
    sched.run_until(sim_duration_s, dispatch)

    # ---- Settle accounting up to sim_duration_s for every node ----
    for n in all_nodes.values():
        _settle_node(n, sim_duration_s)

    # ---- Final metrics ----
    def safe_pdr(d, s):
        return 100.0 * d / s if s > 0 else 0.0

    results["pdr_sub_near"]         = safe_pdr(results["delivered_sub_near"], results["sent_sub_near"])
    results["pdr_sub_far"]          = safe_pdr(results["delivered_sub_far"],  results["sent_sub_far"])
    results["router_duty_cycle_pct"]= 100.0 * results["router_airtime_s"] / sim_duration_s

    # Routing-table snapshots
    results["rt_sub_far_parent"]  = rt_sub_far.best_parent(sim_duration_s)
    results["rt_sub_far_hops"]    = rt_sub_far.my_hop_count(sim_duration_s)
    results["rt_sub_near_parent"] = rt_sub_near.best_parent(sim_duration_s)
    results["rt_sub_near_hops"]   = rt_sub_near.my_hop_count(sim_duration_s)
    results["rt_router_parent"]   = rt_router.best_parent(sim_duration_s)
    results["rt_router_hops"]     = rt_router.my_hop_count(sim_duration_s)

    # Energy per node
    energy = {}
    avg_ma = {}
    for nid, n in all_nodes.items():
        energy[nid] = n.energy_joules()
        avg_ma[nid] = n.average_current_ma(sim_duration_s)
    results["energy_j"]     = energy
    results["avg_current_ma"] = avg_ma
    results["time_in_tx_s"]    = {nid: n.time_in_tx_s    for nid, n in all_nodes.items()}
    results["time_in_rx_s"]    = {nid: n.time_in_rx_s    for nid, n in all_nodes.items()}
    results["time_in_sleep_s"] = {nid: n.time_in_sleep_s for nid, n in all_nodes.items()}

    return results


