# ---------------- MODULE 5 ADDITIONS ----------------
#
# End-to-end ACK timeout.  Worst-case round trip is dominated by the
# SINGLE-TX-CHAIN constraint, not raw air-time:
#
#   SUB_FAR → ROUTER (DATA, ~165 ms ToA)
#   ROUTER  → SUB_FAR (hop-ACK, ~100 ms ToA)
#   ROUTER  → CONTROL (DATA forward, ~165 ms ToA)
#   CONTROL → ROUTER (hop-ACK, ~100 ms ToA)
#   CONTROL → ROUTER (E2E ACK, ~110 ms ToA) — must wait for hop-ACK above
#   ROUTER  → SUB_FAR (E2E ACK relay, ~110 ms ToA) — must wait for ROUTER's
#                     forward DATA TX to complete first
#
# Each TX on the same radio is serialised by `earliest_free_tx_at_s` with a
# 5 ms guard, plus protocol back-off jitter.  Empirically the E2E ACK
# arrives at SUB_FAR at t ≈ 3.0–3.6 s after the originating DATA TX_START.
#
# We therefore set the timeout to 4.0 s — comfortably above the median
# round trip but still small enough that a genuine packet loss is retried
# while the application data is still relevant (heartbeats are every 5 s).
E2E_ACK_TIMEOUT_S = 4.0
MAX_E2E_RETRIES   = 3

# Reference battery — Heltec sandbox uses an 18650 cell at ~2500 mAh nominal.
REFERENCE_BATTERY_MAH = 2500

# Subscriber RX-window duration.  After a subscriber transmits a DATA packet
# it must listen for the hop-ACK.  Real firmware does NOT keep the radio in
# RX for the full E2E_ACK_TIMEOUT_S — that would torch the battery.  Instead
# the firmware would either: (a) re-enter RX briefly when the E2E ACK is
# expected to arrive, or (b) accept eventual delivery and not arm a long
# listen window.  We model this by charging ONE short listen window per
# heartbeat — equal to the hop-ACK timeout — and treat the eventual E2E
# ACK reception as a brief (ToA-sized) RX event handled inline elsewhere.
# This is the realistic-firmware power model; the conservative "always-on"
# model would just set this equal to E2E_ACK_TIMEOUT_S.
