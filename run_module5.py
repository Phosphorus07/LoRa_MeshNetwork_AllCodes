    _result("E2E retransmissions",   r1["e2e_retransmissions"],  "")
    _result("E2E retry exhausted",   r1["e2e_retry_exhausted"],  "")

    # Pass criteria: the E2E loop must close — SUB_FAR's data reaches CONTROL,
    # CONTROL emits E2E ACKs, and SUB_FAR matches enough of them to stop
    # retrying.  We do NOT require zero retransmissions because both
    # subscribers heartbeat every 5 s on the same channel; natural collisions
    # WILL fire occasional E2E timeouts, and the protocol must absorb those
    # without exhausting retries.
    s1_pdr = r1["delivered_sub_far"] / max(1, r1["sent_sub_far"]) * 100.0
    s1_pass = (
        r1["sent_sub_far"] > 0 and
        s1_pdr >= 95.0 and
        r1["e2e_acks_received"] > 0 and
        r1["e2e_retry_exhausted"] == 0
    )
    print(f"\n  Section 1: {'PASS — E2E ACK loop closes cleanly ✓' if s1_pass else 'FAIL'}")

    # =========================================================================
    # SECTION 2 — E2E retry on loss
    # =========================================================================
    _header("SECTION 2 — E2E retry on loss (60 s, drop first 2 E2E ACKs)")
    print(
        "  We drop the first 2 E2E ACKs that CONTROL emits at TX_END.  The\n"
        "  originator should detect the missing ACK and retransmit the DATA.\n"
        "  CONTROL must dedupe so no duplicates are counted as deliveries.\n"
    )

    r2 = run_mesh_simulation_m5(
        sim_duration_s     = 60.0,
        rng_seed           = RNG_SEED,
        ack_enabled        = True,
        e2e_enabled        = True,
        drop_e2e_ack_count = 2,
    )

    _result("SUB_FAR sent (originals)", r2["sent_sub_far"],        " pkts")
    _result("SUB_FAR delivered",        r2["delivered_sub_far"],   " pkts")
    _result("Duplicates at CONTROL",    r2["duplicates_at_control"],"")
    _result("E2E retransmissions",      r2["e2e_retransmissions"], "")
    _result("E2E ACKs dropped (hook)",  r2["e2e_acks_dropped"],    "")
    _result("E2E ACKs received",        r2["e2e_acks_received"],   "")

    s2_pass = (
        r2["e2e_acks_dropped"] == 2 and
        r2["e2e_retransmissions"] > 0 and
        r2["duplicates_at_control"] > 0   # the retried DATA arrives again
    )
    print(f"\n  Section 2: {'PASS — retries triggered, duplicates detected ✓' if s2_pass else 'FAIL'}")

    # =========================================================================
    # SECTION 3 — ROUTER failure → SUB_FAR detects stale route
    # =========================================================================
    _header("SECTION 3 — ROUTER failure (300 s, fail at 90s, NO recovery)")
    print(
        "  ROUTER fails at t=90 s.  After ROUTE_STALE_TIMEOUT_S (60 s) the\n"
        "  SUB_FAR routing table prunes the stale entry.  SUB_FAR should\n"
        "  see no route and defer heartbeats cleanly — no crash, no extra\n"
        "  packets delivered to CONTROL from SUB_FAR after the stale window.\n"
    )

    r3 = run_mesh_simulation_m5(
        sim_duration_s     = 300.0,
        rng_seed           = RNG_SEED,
        ack_enabled        = True,
        e2e_enabled        = True,
        router_fail_at_s   = 90.0,
    )

    _result("SUB_FAR sent",          r3["sent_sub_far"],            " pkts")
    _result("SUB_FAR delivered",     r3["delivered_sub_far"],       " pkts")
    _result("SUB_FAR final hop_count", r3["rt_sub_far_hops"],       "")
    _result("ROUTER stale timeout",  ROUTE_STALE_TIMEOUT_S,         " s")

    # SUB_FAR should have made progress in the first ~90 s, then stalled.
    # Final hop_count should be 255 (NO_ROUTE) because no beacons after fail.
    s3_pass = (
        r3["delivered_sub_far"] > 0 and        # some packets got through before failure
        r3["delivered_sub_far"] < 60 and       # but not all 60 (5s heartbeat * 300s)
        r3["rt_sub_far_hops"] == 255           # SUB_FAR knows it has no route
    )
    print(f"\n  Section 3: {'PASS — SUB_FAR cleanly degrades when ROUTER fails ✓' if s3_pass else 'FAIL'}")

    # =========================================================================
    # SECTION 4 — ROUTER recovery
    # =========================================================================
    _header("SECTION 4 — ROUTER recovery (450 s; fail 90s, recover 250s)")
    print(
        "  After recovery ROUTER resumes beaconing.  Within one beacon\n"
        "  interval SUB_FAR should re-acquire ROUTER as parent and resume\n"
        "  delivery.  Final hop_count back to 2.\n"
    )

    r4 = run_mesh_simulation_m5(
        sim_duration_s       = 450.0,
        rng_seed             = RNG_SEED,
        ack_enabled          = True,
        e2e_enabled          = True,
        router_fail_at_s     = 90.0,
        router_recover_at_s  = 250.0,
    )

    _result("SUB_FAR sent",          r4["sent_sub_far"],          " pkts")
    _result("SUB_FAR delivered",     r4["delivered_sub_far"],     " pkts")
    _result("SUB_FAR final hop_count", r4["rt_sub_far_hops"],     "")
    _result("SUB_FAR final parent",  r4["rt_sub_far_parent"],     "")

    s4_pass = (
        r4["delivered_sub_far"] > r3["delivered_sub_far"]   # more delivered than no-recovery run
        and r4["rt_sub_far_hops"] == 2                       # back on the 2-hop path
        and r4["rt_sub_far_parent"] == NODE_ROUTER_ID
    )
    print(f"\n  Section 4: {'PASS — SUB_FAR rejoins via fresh beacons after ROUTER recovers ✓' if s4_pass else 'FAIL'}")

    # =========================================================================
    # SECTION 5 — SUB_NEAR independence
    # =========================================================================
    _header("SECTION 5 — SUB_NEAR independence during ROUTER outage")
    print(
        "  SUB_NEAR delivers directly to CONTROL (no ROUTER involvement).\n"
        "  ROUTER failure must not affect SUB_NEAR delivery.\n"
    )

    # Reuse Section 3 results (300 s, ROUTER fails at 90 s, never recovers).
    expected_sub_near_min = 50   # ≈300 s / 5 s heartbeat with some boot offset
    _result("SUB_NEAR sent",       r3["sent_sub_near"],         " pkts")
    _result("SUB_NEAR delivered",  r3["delivered_sub_near"],    " pkts")
    _result("SUB_NEAR PDR",        f"{r3['pdr_sub_near']:.1f}", " %")
    _result("SUB_NEAR hop_count",  r3["rt_sub_near_hops"],      "")

    s5_pass = (
        r3["sent_sub_near"] >= expected_sub_near_min and
        r3["pdr_sub_near"] >= 95.0 and
        r3["rt_sub_near_hops"] == 1
    )
    print(f"\n  Section 5: {'PASS — SUB_NEAR unaffected by ROUTER outage ✓' if s5_pass else 'FAIL'}")

    # =========================================================================
    # SECTION 6 — Power budget per node (600 s realistic run)
    # =========================================================================
    _header("SECTION 6 — Power budget per node (600 s, ACK+E2E ON, 8 km)")
    print(
        "  Per-node energy tally using SX1278 datasheet currents:\n"
        f"    TX:    {SX1278_TX_CURRENT_A*1000:.1f} mA  @ +14 dBm\n"
        f"    RX:    {SX1278_RX_CURRENT_A*1000:.1f} mA  (listen)\n"
        f"    Sleep: {SX1278_SLEEP_CURRENT_A*1e6:.1f} µA\n"
        f"    Vsupply: {V_SUPPLY_V:.1f} V\n"
    )

    r6 = run_mesh_simulation_m5(
        sim_duration_s   = 600.0,
        rng_seed         = RNG_SEED,
        ack_enabled      = True,
        e2e_enabled      = True,
    )

    print(f"\n    {'Node':<10} {'TX (s)':>9} {'RX (s)':>9} {'Sleep (s)':>10}  {'Energy (J)':>11}  {'Avg I (mA)':>11}")
    print(f"    {'-'*64}")
    for nid in (NODE_CONTROL_ID, NODE_ROUTER_ID, NODE_SUB_NEAR_ID, NODE_SUB_FAR_ID):
        print(
            f"    {_node_name(nid):<10} "
            f"{r6['time_in_tx_s'][nid]:>9.3f} "
            f"{r6['time_in_rx_s'][nid]:>9.2f} "
            f"{r6['time_in_sleep_s'][nid]:>10.2f}  "
            f"{r6['energy_j'][nid]:>11.4f}  "
            f"{r6['avg_current_ma'][nid]:>11.4f}"
        )

    # Sanity: every node should have spent more time idle than transmitting.
    # CONTROL/ROUTER idle as RX; subscribers idle as SLEEP — check accordingly.
    s6_pass = (
        r6["time_in_tx_s"][NODE_CONTROL_ID]  < r6["time_in_rx_s"][NODE_CONTROL_ID] and
        r6["time_in_tx_s"][NODE_ROUTER_ID]   < r6["time_in_rx_s"][NODE_ROUTER_ID] and
        r6["time_in_tx_s"][NODE_SUB_NEAR_ID] < r6["time_in_sleep_s"][NODE_SUB_NEAR_ID] and
        r6["time_in_tx_s"][NODE_SUB_FAR_ID]  < r6["time_in_sleep_s"][NODE_SUB_FAR_ID]
    )
    print(f"\n  Section 6: {'PASS — energy figures plausible (TX << idle for all nodes) ✓' if s6_pass else 'FAIL'}")

    # =========================================================================
    # SECTION 7 — Battery life projection
    # =========================================================================
    _header("SECTION 7 — Battery life projection (reference cell 2500 mAh)")
    print(
        "  days_remaining = battery_mAh / (avg_current_mA × 24)\n"
        "  This ignores self-discharge and microcontroller current — it is\n"
        "  the radio-only floor.  Real lifetime will be shorter once the\n"
        "  STM32 and any DC-DC losses are accounted for.\n"
    )

    print(f"\n    {'Node':<10} {'Avg I (mA)':>12} {'Days @ 2500 mAh':>20} {'Years':>10}")
    print(f"    {'-'*54}")
    for nid in (NODE_CONTROL_ID, NODE_ROUTER_ID, NODE_SUB_NEAR_ID, NODE_SUB_FAR_ID):
        avg_ma = r6["avg_current_ma"][nid]
        if avg_ma <= 0.0:
            days = float('inf'); years = float('inf')
        else:
            days = REFERENCE_BATTERY_MAH / (avg_ma * 24.0)
            years = days / 365.25
        print(
            f"    {_node_name(nid):<10} "
            f"{avg_ma:>12.4f} "
            f"{days:>20.1f} "
            f"{years:>10.2f}"
        )

    # Sanity threshold: at a SANDBOX heartbeat of 5 s and +14 dBm TX, the
    # TX-time alone is the dominant cost (~120 mA × 165 ms × 120 heartbeats
    # in 600 s ≈ 2.4 C of charge).  This caps the radio-only lifetime around
    # ~15–20 days on a 2500 mAh cell.  A real deployment with a 60 s
    # heartbeat would project >150 days from the same power model.  We
    # therefore PASS at ≥10 days for the sandbox debug rate, which is a
    # plausibility floor — anything below indicates a bookkeeping bug.
    sub_far_avg_ma = r6["avg_current_ma"][NODE_SUB_FAR_ID]
    sub_near_avg_ma = r6["avg_current_ma"][NODE_SUB_NEAR_ID]
    if sub_far_avg_ma <= 0 or sub_near_avg_ma <= 0:
        s7_pass = False
    else:
        sub_far_days  = REFERENCE_BATTERY_MAH / (sub_far_avg_ma  * 24.0)
        sub_near_days = REFERENCE_BATTERY_MAH / (sub_near_avg_ma * 24.0)
        s7_pass = (sub_far_days >= 10.0 and sub_near_days >= 10.0)
    print(f"\n  Section 7: {'PASS — subscriber radios project ≥10 days on 2500 mAh (sandbox rate) ✓' if s7_pass else 'FAIL — subscriber lifetime suspiciously short'}")

    # =========================================================================
    # SECTION 8 — Regression: Module 4 still works with E2E ON
    # =========================================================================
    # The ROUTER duty cycle target is loosened from 10% (Module 4) to 15%
    # because the E2E ACK layer adds a third TX per SUB_FAR heartbeat (relay
    # of the E2E ACK back downstream) on top of the hop-ACK + forward.  With
    # the sandbox's debug-fast 5 s heartbeat that puts the steady-state base
    # right around 10%, leaving no room for the occasional collision retry.
    # In a real deployment the heartbeat would be 30–60 s and the duty cycle
    # would drop below 2%.
    M5_DUTY_CYCLE_LIMIT_PCT = 15.0
    _header("SECTION 8 — Module 4 regression with E2E ON (8 km, 120 s)")
    print(
        "  All Module 4 invariants must still hold with the E2E layer on:\n"
        "    - SUB_FAR PDR ≥ 95%   (2-hop via ROUTER)\n"
        "    - SUB_NEAR PDR ≥ 95%  (1-hop direct)\n"
        f"    - ROUTER duty cycle < {M5_DUTY_CYCLE_LIMIT_PCT:.0f}%  (M5: extra E2E ACK relay TX)\n"
    )

    r8 = run_mesh_simulation_m5(
        sim_duration_s   = 120.0,
        rng_seed         = RNG_SEED,
        ack_enabled      = True,
        e2e_enabled      = True,
    )

    _result("SUB_NEAR PDR",       f"{r8['pdr_sub_near']:.1f}",    " %")
    _result("SUB_FAR  PDR",       f"{r8['pdr_sub_far']:.1f}",     " %")
    _result("Router duty cycle",  f"{r8['router_duty_cycle_pct']:.2f}", " %")
    _result("Router airtime",     f"{r8['router_airtime_s']:.3f}", " s")

    s8_pass = (
        r8["pdr_sub_near"] >= 95.0 and
        r8["pdr_sub_far"]  >= 95.0 and
        r8["router_duty_cycle_pct"] < M5_DUTY_CYCLE_LIMIT_PCT
    )
    print(f"\n  Section 8: {'PASS — Module 4 invariants hold with E2E ACK enabled ✓' if s8_pass else 'FAIL'}")

    # =========================================================================
    # OVERALL
    # =========================================================================
    _sep()
    all_pass = s1_pass and s2_pass and s3_pass and s4_pass and s5_pass and s6_pass and s7_pass and s8_pass
    print(f"  Overall: {'ALL PASS ✓' if all_pass else 'SOME SECTIONS FAILED'}")
    _sep()
    print()
    print("Module 5 complete — sandbox finalised.")
